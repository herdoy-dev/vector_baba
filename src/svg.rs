//! SVG serialization and preview rasterization.

use anyhow::{anyhow, Result};
use resvg::{tiny_skia, usvg};
use visioncortex::PointF64;

/// One output shape, ready to serialize.
#[derive(Clone, Debug)]
pub struct OutPath {
    pub fill: [u8; 3],
    /// Absolute M/L/C/Z path data.
    pub d: String,
    pub translate: (f64, f64),
    pub even_odd: bool,
}

/// Convert the classic tracer's output into our shape list.
pub fn from_vtracer(file: &vtracer::SvgFile) -> Vec<OutPath> {
    file.paths
        .iter()
        .map(|p| {
            let (d, offset) = p.path.to_svg_string(true, PointF64::default(), file.path_precision);
            OutPath { fill: [p.color.r, p.color.g, p.color.b], d, translate: (offset.x, offset.y), even_odd: false }
        })
        .collect()
}

/// Serialize shapes to an SVG document.
///
/// `view_w`/`view_h` are the traced (possibly downscaled) dimensions and become
/// the viewBox. `out_w`/`out_h` are the original pixel dimensions and become
/// the document width/height, so the SVG opens at the source image's size.
pub fn serialize(paths: &[OutPath], view_w: u32, view_h: u32, out_w: u32, out_h: u32, palette: &[[u8; 3]]) -> String {
    serialize_filtered(paths, view_w, view_h, out_w, out_h, palette, &std::collections::HashSet::new(), false)
}

/// [`serialize`] skipping the shapes in `removed`, optionally stroking each
/// shape in its own fill color (hides hairline seams between cut-out shapes).
#[allow(clippy::too_many_arguments)]
pub fn serialize_filtered(
    paths: &[OutPath],
    view_w: u32,
    view_h: u32,
    out_w: u32,
    out_h: u32,
    palette: &[[u8; 3]],
    removed: &std::collections::HashSet<usize>,
    stroke: bool,
) -> String {
    let mut s = String::with_capacity(paths.len() * 256 + 512);
    s.push_str(r#"<?xml version="1.0" encoding="UTF-8"?>"#);
    s.push('\n');
    s.push_str("<!-- Generated by Vector Baba -->\n");
    s.push_str(&format!(
        r#"<svg xmlns="http://www.w3.org/2000/svg" version="1.1" width="{}" height="{}" viewBox="0 0 {} {}">"#,
        out_w, out_h, view_w, view_h
    ));
    s.push('\n');
    if !palette.is_empty() {
        s.push_str("  <!-- palette: ");
        for (i, c) in palette.iter().enumerate() {
            if i > 0 {
                s.push(' ');
            }
            s.push_str(&format!("#{:02x}{:02x}{:02x}", c[0], c[1], c[2]));
        }
        s.push_str(" -->\n");
    }
    for (i, p) in paths.iter().enumerate() {
        if removed.contains(&i) {
            continue;
        }
        let fill = format!("#{:02x}{:02x}{:02x}", p.fill[0], p.fill[1], p.fill[2]);
        let mut attrs = format!(" fill=\"{}\"", fill);
        if p.even_odd {
            attrs.push_str(" fill-rule=\"evenodd\"");
        }
        if stroke {
            attrs.push_str(&format!(" stroke=\"{}\" stroke-width=\"0.5\" stroke-linejoin=\"round\"", fill));
        }
        if p.translate.0 != 0.0 || p.translate.1 != 0.0 {
            attrs.push_str(&format!(" transform=\"translate({},{})\"", p.translate.0, p.translate.1));
        }
        s.push_str(&format!("  <path d=\"{}\"{}/>\n", p.d, attrs));
    }
    s.push_str("</svg>\n");
    s
}

/// Rasterize an SVG string to straight (non-premultiplied) RGBA8 at a size
/// whose longest side is `max_side` pixels. Returns (width, height, rgba).
pub fn rasterize(svg: &str, max_side: u32, background: Option<[u8; 3]>) -> Result<(u32, u32, Vec<u8>)> {
    let tree = usvg::Tree::from_str(svg, &usvg::Options::default())
        .map_err(|e| anyhow!("svg parse: {e}"))?;
    let size = tree.size();
    let (sw, sh) = (size.width(), size.height());
    if sw <= 0.0 || sh <= 0.0 {
        return Err(anyhow!("svg has no size"));
    }
    let scale = (max_side as f32 / sw.max(sh)).min(4.0);
    let w = ((sw * scale).round() as u32).max(1);
    let h = ((sh * scale).round() as u32).max(1);
    let mut pixmap = tiny_skia::Pixmap::new(w, h).ok_or_else(|| anyhow!("pixmap alloc"))?;
    if let Some(bg) = background {
        pixmap.fill(tiny_skia::Color::from_rgba8(bg[0], bg[1], bg[2], 255));
    }
    resvg::render(
        &tree,
        tiny_skia::Transform::from_scale(w as f32 / sw, h as f32 / sh),
        &mut pixmap.as_mut(),
    );
    let mut rgba = Vec::with_capacity((w * h * 4) as usize);
    for p in pixmap.pixels() {
        let c = p.demultiply();
        rgba.extend_from_slice(&[c.red(), c.green(), c.blue(), c.alpha()]);
    }
    Ok((w, h, rgba))
}
